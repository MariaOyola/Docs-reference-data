INSERT INTO rbac_catalog.feature (module_id, code, name, action_level)
SELECT m.id, v.code, v.name, v.action FROM (VALUES
  ('MOD_SCHEDULING','SCH_REPORT_VIEW','Ver reportes de horarios','READ'),
  ('MOD_ENVIRONMENT','ENVIRONMENT_REPORT_VIEW','Ver reportes de ambientes','READ'),
  ('MOD_ACTORS','ACT_REPORT_VIEW','Ver reportes de actores','READ'),
  ('MOD_DOCUMENTS','DOC_REPORT_VIEW','Ver reportes de documentos','READ'),
  ('MOD_DOCUMENTS','DOC_TEMPLATE_VIEW','Ver plantillas de documento','READ'),
  ('MOD_MONITORING','MON_REPORT_VIEW','Ver reportes de monitoreo','READ'),
  ('MOD_MONITORING','MON_CATALOG_MANAGE','Gestionar catalogos de monitoreo','WRITE'),
  ('MOD_MONITORING','MON_NOTIFICATION_VIEW','Ver notificaciones','READ')
) AS v(mod_code, code, name, action)
JOIN rbac_catalog.module m ON m.code = v.mod_code
ON CONFLICT (code) DO NOTHING;

