  ('SYSTEM_ADMIN','ENVIRONMENT_REPORT_VIEW','GLOBAL'),('CENTER_DIRECTOR','ENVIRONMENT_REPORT_VIEW','TRAINING_CENTER'),('COORDINATOR','ENVIRONMENT_REPORT_VIEW','TRAINING_CENTER'),
  ('SYSTEM_ADMIN','ACT_REPORT_VIEW','GLOBAL'),('CENTER_DIRECTOR','ACT_REPORT_VIEW','TRAINING_CENTER'),('COORDINATOR','ACT_REPORT_VIEW','TRAINING_CENTER'),
  ('SYSTEM_ADMIN','MON_REPORT_VIEW','GLOBAL'),('CENTER_DIRECTOR','MON_REPORT_VIEW','TRAINING_CENTER'),('COORDINATOR','MON_REPORT_VIEW','TRAINING_CENTER'),
  ('SYSTEM_ADMIN','DOC_REPORT_VIEW','GLOBAL'),('CENTER_DIRECTOR','DOC_REPORT_VIEW','TRAINING_CENTER'),('ADMIN_STAFF','DOC_REPORT_VIEW','GLOBAL'),
  ('SYSTEM_ADMIN','DOC_TEMPLATE_VIEW','GLOBAL'),('ADMIN_STAFF','DOC_TEMPLATE_VIEW','GLOBAL'),
  ('SYSTEM_ADMIN','MON_CATALOG_MANAGE','GLOBAL'),('ADMIN_STAFF','MON_CATALOG_MANAGE','GLOBAL'),
  ('SYSTEM_ADMIN','MON_NOTIFICATION_VIEW','GLOBAL'),('CENTER_DIRECTOR','MON_NOTIFICATION_VIEW','TRAINING_CENTER'),('COORDINATOR','MON_NOTIFICATION_VIEW','TRAINING_CENTER'),('INSTRUCTOR','MON_NOTIFICATION_VIEW','OWN_FICHAS'),('LEARNER','MON_NOTIFICATION_VIEW','OWN_FICHA_AS_LEARNER'),('ADMIN_STAFF','MON_NOTIFICATION_VIEW','GLOBAL')
